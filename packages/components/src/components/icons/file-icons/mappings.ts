// Returns true when the file name maps to a known icon by exact name or
// (compound) extension. Used as a noise filter when auto-detecting bare file
// paths in prose/inline code: a recognized type is a strong signal the token
// is really a file (e.g. `tsconfig.json`, `foo.ts`) rather than a method
// reference like `Math.max` or a sentence fragment.
export const isRecognizedFilePath = (fileName: string): boolean => {
  const lower = fileName.toLowerCase();

  if (fileNameMap[lower] || fileNameMap[fileName]) {
    return true;
  }

  for (const ext of Object.keys(compoundExtensionMap)) {
    if (lower.endsWith('.' + ext)) {
      return true;
    }
  }

  const lastDotIndex = lower.lastIndexOf('.');
  if (lastDotIndex > 0 && lastDotIndex < lower.length - 1) {
    const ext = lower.slice(lastDotIndex + 1);
    if (extensionMap[ext]) {
      return true;
    }
  }

  return false;
};
