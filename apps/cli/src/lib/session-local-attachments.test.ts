import { FileDownloadRequestSchema, FILE_DOWNLOAD_CHUNK_BYTES } from '@lody/shared';
import { afterEach, expect, it } from 'vitest';
import { mkdtemp, writeFile, readFile, rm, symlink, unlink, realpath } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import {
  prepareLocalAttachment,
  resolveLocalAttachment,
  downloadLocalAttachment,
} from './session-local-attachments';

const roots: string[] = [];
afterEach(async () => {
  await Promise.all(roots.splice(0).map((root) => rm(root, { recursive: true, force: true })));
});
async function fixture() {
  const root = await mkdtemp(path.join(tmpdir(), 'lody-attachment-test-'));
  roots.push(root);
  const source = path.join(root, 'original # 文.txt');
  await writeFile(source, 'first');
  const scope = {
    machineId: 'machine',
    workspaceId: 'workspace',
    sessionId: 'session',
  };
  const input = {
    machineId: scope.machineId,
    path: source,
    kind: 'file' as const,
    fileName: 'original.txt',
    mimeType: 'text/plain',
  };
  return {
    root,
    source,
    scope,
    input,
    attachment: { ...input, type: 'local_attachment' as const, sizeBytes: 5 },
  };
}
it('resolves an original path and sees later content without making a snapshot', async () => {
  const f = await fixture();
  const receipt = f.attachment;
  await writeFile(f.source, 'changed');
  const resolved = await resolveLocalAttachment(receipt, f.scope.machineId);
  expect(resolved.path).toBe(await realpath(f.source));
  expect(await readFile(resolved.path, 'utf8')).toBe('changed');
  expect(receipt.path).toBe(f.source);
});
it('resolves symlinks at read time while refusing another machine and missing files', async () => {
  const f = await fixture();
  const receipt = f.attachment;
  await expect(resolveLocalAttachment(receipt, 'other')).rejects.toThrow();
  const other = f.source + '.other';
  await writeFile(other, 'private');
  await unlink(f.source);
  await symlink(other, f.source);
  const resolved = await resolveLocalAttachment(receipt, f.scope.machineId);
  expect(resolved.path).toBe(await realpath(other));
  expect(await readFile(resolved.path, 'utf8')).toBe('private');
  await unlink(f.source);
  await expect(resolveLocalAttachment(receipt, f.scope.machineId)).rejects.toThrow();
});
it('retains generated bytes independently of their staging file', async () => {
  const f = await fixture();
  const receipt = await prepareLocalAttachment(f.input, f.root);
  await unlink(f.source);
  const resolved = await resolveLocalAttachment(receipt, f.scope.machineId);
  expect(await readFile(resolved.path, 'utf8')).toBe('first');
  expect(resolved.path).not.toBe(f.source);
});

it('downloads local content in existing RPC chunks without copying or publishing a cloud receipt', async () => {
  const f = await fixture();
  const bytes = Buffer.alloc(FILE_DOWNLOAD_CHUNK_BYTES + 17, 0x57);
  await writeFile(f.source, bytes);
  const attachment = f.attachment;
  const request = FileDownloadRequestSchema.parse({
    sessionId: f.scope.sessionId,
    path: attachment.fileName,
    attachment,
    offset: 0,
  });
  const first = await downloadLocalAttachment(request, f.scope.machineId);
  expect(first.status).toBe('ok');
  if (first.status !== 'ok') throw new Error('First chunk unavailable');
  const last = await downloadLocalAttachment(
    {
      ...request,
      offset: FILE_DOWNLOAD_CHUNK_BYTES,
      revision: first.revision,
    },
    f.scope.machineId
  );
  if (last.status !== 'ok') throw new Error('Last chunk unavailable');
  expect(
    Buffer.concat([Buffer.from(first.data, 'base64'), Buffer.from(last.data, 'base64')])
  ).toEqual(bytes);
  expect(await resolveLocalAttachment(attachment, f.scope.machineId)).toMatchObject({
    path: await realpath(f.source),
  });
});
