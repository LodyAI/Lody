import { FileDownloadRequestSchema, FILE_DOWNLOAD_CHUNK_BYTES } from '@lody/shared';
import { afterEach, expect, it } from 'vitest';
import { mkdtemp, writeFile, readFile, rm, symlink, unlink, realpath } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import { LocalAttachmentStore } from './session-local-attachments';

const roots: string[] = [];
afterEach(async () => {
  await Promise.all(roots.splice(0).map((root) => rm(root, { recursive: true, force: true })));
});
async function fixture() {
  const root = await mkdtemp(path.join(tmpdir(), 'lody-attachment-test-'));
  roots.push(root);
  const source = path.join(root, 'original # 文.txt');
  await writeFile(source, 'first');
  const scope = {
    machineId: 'machine',
    workspaceId: 'workspace',
    sessionId: 'session',
    turnId: 'turn',
  };
  const input = {
    ...scope,
    referenceId: randomUUID(),
    path: source,
    managed: false,
    kind: 'file' as const,
    fileName: 'original.txt',
    mimeType: 'text/plain',
  };
  return {
    store: new LocalAttachmentStore({ ...scope, accountId: 'test' }, root),
    root,
    source,
    scope,
    input,
  };
}
it('resolves an original at its original path across reopen and sees later content without making a snapshot', async () => {
  const f = await fixture();
  const receipt = await f.store.register(f.input);
  await writeFile(f.source, 'changed');
  const resolved = await new LocalAttachmentStore(
    { ...f.scope, accountId: 'test' },
    f.root
  ).resolve(f.scope, receipt);
  expect(resolved.path).toBe(await realpath(f.source));
  expect(await readFile(resolved.path, 'utf8')).toBe('changed');
  expect(receipt).not.toHaveProperty('path');
});
it('refuses cross-turn use, a different machine, missing files and redirected symlinks', async () => {
  const f = await fixture();
  const link = f.source + '.link';
  await symlink(f.source, link);
  const receipt = await f.store.register({ ...f.input, path: link });
  await expect(f.store.resolve({ ...f.scope, turnId: 'forged' }, receipt)).rejects.toThrow();
  await expect(
    new LocalAttachmentStore({ ...f.scope, machineId: 'other', accountId: 'test' }, f.root).resolve(
      f.scope,
      receipt
    )
  ).rejects.toThrow();
  const other = f.source + '.other';
  await writeFile(other, 'private');
  await unlink(link);
  await symlink(other, link);
  await expect(f.store.resolve(f.scope, receipt)).rejects.toThrow();
  await unlink(link);
  await expect(f.store.resolve(f.scope, receipt)).rejects.toThrow();
});
it('retains generated bytes independently of their staging file', async () => {
  const f = await fixture();
  const receipt = await f.store.register({ ...f.input, managed: true });
  await unlink(f.source);
  const resolved = await f.store.resolve(f.scope, receipt);
  expect(await readFile(resolved.path, 'utf8')).toBe('first');
  expect(resolved.path).not.toBe(f.source);
});

it('does not replace accepted generated bytes when a reference is reused with another source', async () => {
  const f = await fixture();
  const receipt = await f.store.register({ ...f.input, managed: true });
  await writeFile(f.source, 'replacement');
  await expect(f.store.register({ ...f.input, managed: true })).rejects.toThrow('conflicts');
  const resolved = await f.store.resolve(f.scope, receipt);
  expect(await readFile(resolved.path, 'utf8')).toBe('first');
});

it('explicitly authorizes a same-machine resend without transferring or invalidating the original', async () => {
  const f = await fixture();
  const original = await f.store.register({ ...f.input, managed: true });
  const target = { ...f.scope, sessionId: 'fork', turnId: 'resend' };
  const copied = await f.store.inherit(original, target);
  const from = await f.store.resolve(f.scope, original);
  const to = await f.store.resolve(target, copied);
  expect(to.path).toBe(from.path);
  await expect(f.store.resolve(target, original)).rejects.toThrow();
  await expect(
    new LocalAttachmentStore(
      { ...f.scope, machineId: 'remote', accountId: 'test' },
      f.root
    ).inherit(original, target)
  ).rejects.toThrow();
});

it('downloads registered content in existing RPC chunks without copying or publishing a cloud receipt', async () => {
  const f = await fixture();
  const bytes = Buffer.alloc(FILE_DOWNLOAD_CHUNK_BYTES + 17, 0x57);
  await writeFile(f.source, bytes);
  const attachment = await f.store.register(f.input);
  const request = FileDownloadRequestSchema.parse({
    sessionId: f.scope.sessionId,
    path: attachment.fileName,
    attachment,
    offset: 0,
  });
  const first = await f.store.download(request);
  expect(first.status).toBe('ok');
  if (first.status !== 'ok') throw new Error('First chunk unavailable');
  const last = await f.store.download({
    ...request,
    offset: FILE_DOWNLOAD_CHUNK_BYTES,
    revision: first.revision,
  });
  if (last.status !== 'ok') throw new Error('Last chunk unavailable');
  expect(
    Buffer.concat([Buffer.from(first.data, 'base64'), Buffer.from(last.data, 'base64')])
  ).toEqual(bytes);
  expect(await f.store.resolve(f.scope, attachment)).toMatchObject({
    path: await realpath(f.source),
  });
});

it('keeps account and workspace ownership inside the store', async () => {
  const f = await fixture();
  const receipt = await f.store.register(f.input);
  for (const environment of [
    { ...f.scope, accountId: 'another-account' },
    { ...f.scope, accountId: 'test', workspaceId: 'another-workspace' },
  ]) {
    const other = new LocalAttachmentStore(environment, f.root);
    await expect(other.resolve(f.scope, receipt)).rejects.toThrow();
  }
  expect(await f.store.resolve(f.scope, receipt)).toMatchObject({ sizeBytes: 5 });
});
