import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const mobileRoot = join(scriptDir, '..');
const androidRoot = join(mobileRoot, 'android');
const settingsPath = join(androidRoot, 'capacitor.settings.gradle');
const capacitorBuildPath = join(androidRoot, 'app', 'capacitor.build.gradle');

const toPackagePath = (relativePath) => {
  const normalized = relativePath.replaceAll('\\', '/');
  const nestedNodeModules = normalized.lastIndexOf('/node_modules/');
  const packagePath =
    nestedNodeModules >= 0
      ? normalized.slice(nestedNodeModules + '/node_modules/'.length)
      : normalized.replace(/^\.\.\/node_modules\//, '');

  if (packagePath === normalized) {
    return relativePath;
  }

  return `../node_modules/${packagePath}`;
};

const normalizeSettingsGradle = () => {
  const source = readFileSync(settingsPath, 'utf8');
  const entries = [];

  const generatedPattern =
    /include\s+':([^']+)'\s*\r?\nproject\(':[^']+'\)\.projectDir\s*=\s*new File\('([^']+)'\)/g;
  for (const match of source.matchAll(generatedPattern)) {
    entries.push({ name: match[1], path: toPackagePath(match[2]) });
  }

  if (entries.length === 0) {
    const normalizedPattern = /includeAndroidProject\('([^']+)',\s*'([^']+)'\)/g;
    for (const match of source.matchAll(normalizedPattern)) {
      entries.push({ name: match[1], path: toPackagePath(match[2]) });
    }
  }

  if (entries.length === 0) {
    throw new Error(`No Capacitor Android project includes found in ${settingsPath}`);
  }

  const body = entries
    .map(({ name, path }) => `includeAndroidProject('${name}', '${path}')`)
    .join('\n\n');

  const helper = [
    '// DO NOT EDIT THIS FILE! IT IS GENERATED EACH TIME "capacitor update" IS RUN',
    '// Run scripts/normalize-android-gradle-paths.mjs after Capacitor rewrites it.',
    '// Capacitor resolves pnpm packages to virtual-store realpaths; Gradle should consume',
    '// package symlinks so peer-layout changes do not produce empty included projects.',
    'def includeAndroidProject = { String name, String relativePath ->',
    '    include ":${name}"',
    '    def projectDir = new File(settingsDir, relativePath)',
    "    if (!new File(projectDir, 'build.gradle').isFile() && !new File(projectDir, 'build.gradle.kts').isFile()) {",
    '        throw new GradleException("Missing Gradle project \':${name}\' at ${projectDir}. Run `corepack pnpm install` from the repository root, then retry the Android build.")',
    '    }',
    '    project(":${name}").projectDir = projectDir',
    '}',
  ].join('\n');

  writeFileSync(settingsPath, `${helper}\n\n${body}\n`);
};

const normalizeCapacitorBuildGradle = () => {
  const source = readFileSync(capacitorBuildPath, 'utf8');
  const normalized = source.replace(
    /apply from: "([^"]*node_modules\/(?:\.pnpm\/[^"]+\/node_modules\/)?onesignal-cordova-plugin\/build-extras-onesignal\.gradle)"/g,
    'apply from: "../../node_modules/onesignal-cordova-plugin/build-extras-onesignal.gradle"'
  );

  writeFileSync(capacitorBuildPath, normalized);
};

normalizeSettingsGradle();
normalizeCapacitorBuildGradle();
