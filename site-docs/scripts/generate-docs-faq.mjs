import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { extractFaqFromMdx } from './extract-docs-faq.mjs';
import { slugFromMdxFile } from './site-paths.mjs';

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outFile = path.join(packageRoot, 'lib', 'docs-faq.generated.ts');

function listMdxFiles(dir) {
  const files = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const entryPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...listMdxFiles(entryPath));
    } else if (entry.isFile() && entry.name.endsWith('.mdx')) {
      files.push(entryPath);
    }
  }
  return files.sort((a, b) => a.localeCompare(b));
}

const docsFaqByPath = {};
for (const locale of ['en', 'zh']) {
  const localeRoot = path.join(packageRoot, 'content', 'docs', locale);
  const base = locale === 'zh' ? '/zh/docs' : '/docs';
  for (const file of listMdxFiles(localeRoot)) {
    const items = extractFaqFromMdx(readFileSync(file, 'utf8'));
    if (items.length === 0) continue;
    const slug = slugFromMdxFile(file, localeRoot);
    const sitePath = slug.length === 0 ? base : `${base}/${slug}`;
    docsFaqByPath[sitePath] = items;
  }
}

const body = `// Generated by scripts/generate-docs-faq.mjs. Do not edit.
// FAQPage items keyed by canonical docs path (no trailing slash).

export const docsFaqByPath: Record<string, { question: string; answer: string }[]> = ${JSON.stringify(
  docsFaqByPath,
  null,
  2
)};
`;

writeFileSync(outFile, body, 'utf8');
process.stdout.write(
  `Generated lib/docs-faq.generated.ts from ${Object.keys(docsFaqByPath).length} FAQ docs\n`
);
