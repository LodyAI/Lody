function glyphFor(path: string) {
  const name = path.toLowerCase();
  if (name.endsWith('.tsx')) return <ReactTsGlyph />;
  if (name.endsWith('.ts')) return <TsGlyph />;
  if (name.endsWith('.md') || name.endsWith('.mdx')) return <MarkdownGlyph />;
  return <DocumentGlyph />;
}

